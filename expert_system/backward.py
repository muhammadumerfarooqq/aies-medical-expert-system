"""Hybrid reasoning: forward chaining first, then backward chaining on close calls.

Forward chaining (engine.py) reasons from the reported facts to conclusions.
When the two best diseases are almost tied, backward chaining works the other
way: it takes each disease as a GOAL and searches the rules for facts that
could still be asked about, so the questions are generated from the rules and
never written by hand. This file contains no medical names at all.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Callable, Optional

from expert_system.engine import DiagnosisResult, DiseaseResult, diagnose, display_name, parse_input

CLOSE_MARGIN = 15.0   # a gap of this many percentage points or less is "close"
MAX_QUESTIONS = 3     # at most this many questions per consultation


@dataclass
class CloseCall:
    """The two best diseases when they are nearly tied (first.cf >= second.cf)."""
    first: DiseaseResult
    second: DiseaseResult
    gap: float                     # (cf_a - cf_b) / (cf_a + cf_b) * 100


@dataclass
class Question:
    """One question generated by backward chaining."""
    symptom_id: str
    label: str
    input_type: str                # "intensity" or "yes_no"
    goal: str                      # disease id this question could support
    rule_id: str                   # rule that would use the answer
    rule_cf: float
    completes_rule: bool           # every other IF condition is already true
    path: list[str]                # goal <- rule needs sub-goal <- rule needs symptom


@dataclass
class Step:
    """One asked question, the answer and the re-run forward-chaining result."""
    question: Question
    answer: str
    result_after: DiagnosisResult
    gap_after: Optional[float]


@dataclass
class HybridResult:
    """Outcome of a whole hybrid session."""
    initial_result: DiagnosisResult
    steps: list[Step]
    final_result: DiagnosisResult
    outcome: str                   # not_close / separated / no_more_questions / max_questions / stopped
    final_symptoms: dict[str, str]

    def to_dict(self) -> dict:
        """Return the session as plain dicts/lists."""
        return asdict(self)


def gap_between(first: DiseaseResult, second: DiseaseResult) -> float:
    """Relative gap in percentage points between two diseases' CFs."""
    return (first.cf - second.cf) / (first.cf + second.cf) * 100


def top_two_gap(result: DiagnosisResult) -> Optional[float]:
    """Gap between the two highest-CF shown diseases, or None if fewer than two."""
    if len(result.diseases) < 2:
        return None
    ranked = sorted(result.diseases, key=lambda d: -d.cf)
    return gap_between(ranked[0], ranked[1])


def close_call(result: DiagnosisResult) -> Optional[CloseCall]:
    """Return a CloseCall if 2+ diseases are shown and the top two are within CLOSE_MARGIN."""
    if len(result.diseases) < 2:
        return None
    ranked = sorted(result.diseases, key=lambda d: -d.cf)
    gap = gap_between(ranked[0], ranked[1])
    if gap <= CLOSE_MARGIN + 1e-9:
        return CloseCall(ranked[0], ranked[1], gap)
    return None


def find_questions(kb: dict, result: DiagnosisResult, symptoms: dict,
                   denied: set[str]) -> list[Question]:
    """Generate questions that could separate the two close diseases.

    Backward chaining, one goal per close disease:
      BC STEP 1  Start with a goal: each of the two close diseases.
      BC STEP 2  Search for rules whose THEN part is the goal.
      BC STEP 3  Check each IF condition: a symptom already reported (CF at or
                 above the firing threshold) is true.
      BC STEP 4  Not known: an intermediate fact becomes a SUB-GOAL (steps 2-4
                 again); an unreported symptom becomes a QUESTION.
      BC STEP 5  Repeat until every sub-goal has been explored.

    Sub-goals are explored even when they are ALREADY proven. The aim is not to
    prove one hypothesis but to find ADDITIONAL evidence that pulls the two
    hypotheses apart; a proven sub-goal may still have other rules that a new
    answer could strengthen.

    Skipped: symptoms already reported, denied symptoms, symptoms whose
    ask_only_if parent was not reported, and symptoms under BOTH goals (the
    answer would help both diseases, so it does not discriminate).
    """
    call = close_call(result)
    if call is None:
        return []
    threshold = kb["meta"]["cf_conventions"]["rule_fire_threshold"]
    reported, _, _ = parse_input(kb, symptoms)
    rules = kb["rules"]
    rule_order = {rule["id"]: i for i, rule in enumerate(rules)}
    goals = [call.first.disease_id, call.second.disease_id]   # higher CF first

    def is_true(item: str) -> bool:
        """A symptom or fact is true if it is in working memory at or above the threshold."""
        return result.working_memory.get(item, 0.0) >= threshold - 1e-9

    def askable(symptom_id: str) -> bool:
        """True if the symptom may be asked: not reported, not denied, parent reported."""
        if symptom_id in reported or symptom_id in denied:
            return False
        parent = kb["symptoms"][symptom_id].get("ask_only_if")
        return parent is None or parent in reported

    def explore(fact: str, path: list[str], goal: str, found: list[Question]) -> None:
        """BC STEPS 2-5 for one goal or sub-goal."""
        for rule in rules:
            if rule["then"] != fact:                          # BC STEP 2
                continue
            for premise in rule["if"]:
                step_path = path + [f"{rule['id']} needs {display_name(kb, premise)}"]
                if premise in kb["symptoms"]:                 # BC STEP 3
                    if is_true(premise) or not askable(premise):
                        continue
                    others = [p for p in rule["if"] if p != premise]
                    found.append(Question(
                        premise, kb["symptoms"][premise]["label"],
                        kb["symptoms"][premise]["input"], goal, rule["id"], rule["cf"],
                        all(is_true(p) for p in others), step_path))
                else:                                         # BC STEP 4: sub-goal
                    explore(premise, step_path, goal, found)

    per_goal: dict[str, list[Question]] = {}
    for goal in goals:                                        # BC STEP 1
        per_goal[goal] = []
        explore(goal, [display_name(kb, goal)], goal, per_goal[goal])

    # Drop symptoms that appear under both goals.
    shared = {q.symptom_id for q in per_goal[goals[0]]} & {q.symptom_id for q in per_goal[goals[1]]}
    candidates = [q for goal in goals for q in per_goal[goal] if q.symptom_id not in shared]
    candidates.sort(key=lambda q: (not q.completes_rule, -q.rule_cf,
                                   goals.index(q.goal), rule_order[q.rule_id]))
    questions: list[Question] = []
    seen: set[str] = set()
    for q in candidates:
        if q.symptom_id not in seen:
            seen.add(q.symptom_id)
            questions.append(q)
    return questions


def run_session(kb: dict, symptoms: dict, answer_fn: Callable[[Question], Optional[str]],
                max_questions: int = MAX_QUESTIONS,
                on_step: Optional[Callable[[Step], None]] = None) -> HybridResult:
    """Forward chain, then ask questions while the top two diseases stay close.

    answer_fn(question) returns "no", an intensity label, "yes", or None to stop.
    Forward chaining is re-run after every answer. on_step (optional) is called
    after each answered question, e.g. to print the updated ranking.
    """
    known = dict(symptoms)
    denied: set[str] = set()
    result = diagnose(kb, known)
    initial = result
    steps: list[Step] = []
    if close_call(result) is None:
        return HybridResult(initial, steps, result, "not_close", known)

    while True:
        if close_call(result) is None:
            outcome = "separated"
            break
        if len(steps) >= max_questions:
            outcome = "max_questions"
            break
        questions = find_questions(kb, result, known, denied)
        if not questions:
            outcome = "no_more_questions"
            break
        question = questions[0]
        answer = answer_fn(question)
        if answer is None:
            outcome = "stopped"
            break
        if answer == "no":
            denied.add(question.symptom_id)
        else:
            known[question.symptom_id] = answer
        result = diagnose(kb, known)
        step = Step(question, answer, result, top_two_gap(result))
        steps.append(step)
        if on_step is not None:
            on_step(step)
    return HybridResult(initial, steps, result, outcome, known)
